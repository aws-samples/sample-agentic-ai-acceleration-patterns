// Smithy-generated SSDK output is not linted (regenerated by `smithy build`)
project.eslint?.addIgnorePattern('src/smithy/**/*');

// Generated output is not committed - `smithy build` recreates it before compile
project.gitignore.exclude('src/smithy/');

// Local working notes and agent config - not part of the sample
project.gitignore.exclude('TODO.md');
project.gitignore.exclude('.kiro/');

// The integ-runner snapshot is machine output (assertion-provider templates
// plus bundled CDK assets, including a vendored AWS CLI layer) and is NOT
// shipped with the sample: it would carry megabytes of third-party code and
// trip security scanners on generated artifacts. It stays local so
// --update-on-failed keeps re-runs fast; the integ task always runs --force,
// so no workflow depends on a committed snapshot.
project.gitignore.exclude('test/*.snapshot/');

// Regenerate the SSDK + OpenAPI spec from the model before every compile
project.preCompileTask.exec('smithy build');

// ---------------------------------------------------------------------------
// Build-only placeholder stack inputs (S3). src/main.ts fails fast when the
// vendor IdP context is missing, so `npx projen build` (which runs
// `cdk synth` without deploy context) supplies explicit, clearly labelled
// placeholders. These NEVER reach a deployment: `npx cdk deploy` runs its own
// synth with the real `--context` values (see README "Deploy").
// ---------------------------------------------------------------------------
const buildOnlyPlaceholderContext = [
  '--context vendorIdpIssuerUrl=https://build-placeholder.invalid',
  '--context vendorIdpAudience=build-placeholder',
].join(' ');
project.tasks.tryFind('synth:silent')?.reset(`cdk synth -q ${buildOnlyPlaceholderContext}`);
project.tasks.tryFind('synth')?.reset(`cdk synth ${buildOnlyPlaceholderContext}`);

// End-to-end integration test (test/integ.tenant.ts) - deploys real
// infrastructure in TWO accounts (the current one and CP_INTEG_ACCOUNT_B,
// spec §10) and drives the API through the full lifecycle, hooks included
// (ADR-044). The task runs test/integ-scripts/run-integ.sh, which: fails fast
// when AWS_REGION (the single Region integ-runner's multi-Region defaults must
// never replace, integration-test.md) or the second account is unset; takes
// this run's id (CP_INTEG_RUN_ID, generated when unset), which names the fleet
// `cp-integ-<run id>` and every stack, so two runs can share both accounts and
// a Region; refuses to start while a stack of THIS run exists; runs
// integ-runner; and checks what of this run's fleet is left in account A.
const integ = project.addTask('integ', {
  description:
    'Run the deployment integration test in $AWS_REGION across the current AWS account and $CP_INTEG_ACCOUNT_B (~2 h; run it detached)',
});
integ.exec('bash test/integ-scripts/run-integ.sh');

// Session tag integration test (test/integ.session-tags.ts, ADR-0051): a
// small fleet of its own, same accounts, guards and leftover check; it starts
// builds in the stack's provisioning projects and calls no API operation.
const integSessionTags = project.addTask('integ:session-tags', {
  description:
    'Run the session tag integration test in $AWS_REGION across the current AWS account and $CP_INTEG_ACCOUNT_B (~30 min)',
});
integSessionTags.exec('bash test/integ-scripts/run-integ.sh integ.session-tags.ts');

project.synth();
