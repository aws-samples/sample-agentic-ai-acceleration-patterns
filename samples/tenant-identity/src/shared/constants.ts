/** Crockford base32 ULID, as generated by `ulid`. */
export const ULID_PATTERN = /^[0-9A-HJKMNP-TV-Z]{26}$/;

export function isTenantId(value: unknown): value is string {
  return typeof value === 'string' && ULID_PATTERN.test(value);
}

/** Membership group: every topology except pool-per-tenant (ADR-0014). */
export function tenantGroupName(tenantId: string): string {
  return `t-${tenantId}`;
}

/** Admin role group: every topology (ADR-0015). */
export function adminGroupName(tenantId: string): string {
  return `admin-${tenantId}`;
}

export const TENANT_GROUP_PATTERN = /^t-([0-9A-HJKMNP-TV-Z]{26})$/;
export const ADMIN_GROUP_PATTERN = /^admin-([0-9A-HJKMNP-TV-Z]{26})$/;

/** shared-pool: the immutable custom attribute that names the tenant (spec §7.2). */
export const TENANT_ATTRIBUTE_NAME = 'tenantId';
export const TENANT_ATTRIBUTE = `custom:${TENANT_ATTRIBUTE_NAME}`;

/** pool-per-tenant: pool name prefix (spec §7.1). */
export const TENANT_POOL_NAME_PREFIX = 'tenant-identity-';

/** Tag on every pool the sample creates (N-3, N-8). */
export const SAMPLE_TAG_KEY = 'sample';
export const SAMPLE_TAG_VALUE = 'tenant-identity';
/**
 * Second tag on every pool: the owning stack's name. The pool-per-tenant IAM
 * conditions require it, so one stack's roles cannot reach another stack's
 * pools in the same account (N-3).
 */
export const STACK_TAG_KEY = 'tenant-identity:stack';
/**
 * Third tag on every pool-per-tenant pool: the tenant that owns it
 * (ADR-0026). The tenant-scoped role matches it against its session tag.
 */
export const TENANT_TAG_KEY = 'tenant-identity:tenant';
/**
 * The session tag the tenant-user function sets when it assumes the
 * tenant-scoped role (ADR-0026). A plain key, no ':' or '-', so it reads
 * cleanly inside the `${aws:PrincipalTag/...}` policy variable.
 */
export const TENANT_SESSION_TAG_KEY = 'TenantId';
/** Session length for the tenant-scoped role: the STS minimum (ADR-0026). */
export const TENANT_SESSION_SECONDS = 900;

/** The per-tenant API Gateway key's name (ADR-0025). */
export function apiKeyName(tenantId: string): string {
  return `tenant-${tenantId}`;
}

/** The stack's usage plan for `/tenant/*` (ADR-0025); the standard tier's in `tiered`. */
export function tenantUsagePlanName(stackName: string): string {
  return `${stackName}-tenant`;
}

/** `tiered` only: the premium tier's usage plan for `/tenant/*` (ADR-0025, ADR-0027). */
export function premiumUsagePlanName(stackName: string): string {
  return `${stackName}-tenant-premium`;
}

/** Token lifetimes (N-1). */
export const ACCESS_TOKEN_MINUTES = 5;
export const ID_TOKEN_MINUTES = 5;
export const REFRESH_TOKEN_DAYS = 1;

export function issuerFor(region: string, userPoolId: string): string {
  return `https://cognito-idp.${region}.amazonaws.com/${userPoolId}`;
}

/** The pool id is the last path segment of a Cognito issuer URL. */
export function userPoolIdFromIssuer(issuer: string): string | undefined {
  const match = /^https:\/\/cognito-idp\.[a-z0-9-]+\.amazonaws\.com\/([\w-]+_[0-9A-Za-z]+)$/.exec(issuer);
  return match?.[1];
}

