/** Tag on every pool the sample creates (N-3, N-8). */
export const SAMPLE_TAG_KEY = 'sample';
export const SAMPLE_TAG_VALUE = 'tenant-identity';

/** Token lifetimes (N-1). */
export const ACCESS_TOKEN_MINUTES = 5;
export const ID_TOKEN_MINUTES = 5;
