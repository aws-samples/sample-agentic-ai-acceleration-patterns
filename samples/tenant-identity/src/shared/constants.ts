export function issuerFor(region: string, userPoolId: string): string {
  return `https://cognito-idp.${region}.amazonaws.com/${userPoolId}`;
}

/** The pool id is the last path segment of a Cognito issuer URL. */
export function userPoolIdFromIssuer(issuer: string): string | undefined {
  const match = /^https:\/\/cognito-idp\.[a-z0-9-]+\.amazonaws\.com\/([\w-]+_[0-9A-Za-z]+)$/.exec(issuer);
  return match?.[1];
}

