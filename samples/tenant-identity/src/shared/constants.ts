/**
 * The fixed vocabulary every module shares: topology names, group names,
 * scopes, the narrowing keys, and the RFC 8693 URNs. These are deploy-time
 * constants, never inputs (spec P-7, §8.1).
 */

// ---------------------------------------------------------------------------
// Topology (spec P-7, ADR-0001)
// ---------------------------------------------------------------------------

export const TOPOLOGIES = ['pool-per-tenant', 'shared-pool', 'shared-pool-multi-tenant'] as const;
export type Topology = (typeof TOPOLOGIES)[number];

/** Returns the topology, or throws with the accepted values listed. */
export function parseTopology(value: unknown): Topology {
  if (typeof value === 'string' && (TOPOLOGIES as readonly string[]).includes(value)) {
    return value as Topology;
  }
  const shown = value === undefined || value === '' ? '(missing)' : `'${String(value)}'`;
  throw new Error(
    `Invalid topology ${shown}. Pass exactly one of: ${TOPOLOGIES.join(', ')} ` +
      '(for example --context topology=shared-pool).',
  );
}

// ---------------------------------------------------------------------------
// Identifiers and Cognito names (spec §4, §7)
// ---------------------------------------------------------------------------

/** Crockford base32 ULID, as generated by `ulid`. */
export const ULID_PATTERN = /^[0-9A-HJKMNP-TV-Z]{26}$/;

export function isTenantId(value: unknown): value is string {
  return typeof value === 'string' && ULID_PATTERN.test(value);
}

/** Membership group: every topology except pool-per-tenant (ADR-0014). */
export function tenantGroupName(tenantId: string): string {
  return `t-${tenantId}`;
}

/** Admin role group: every topology (ADR-0015). */
export function adminGroupName(tenantId: string): string {
  return `admin-${tenantId}`;
}

export const TENANT_GROUP_PATTERN = /^t-([0-9A-HJKMNP-TV-Z]{26})$/;
export const ADMIN_GROUP_PATTERN = /^admin-([0-9A-HJKMNP-TV-Z]{26})$/;

/** shared-pool: the immutable custom attribute that names the tenant (spec §7.2). */
export const TENANT_ATTRIBUTE_NAME = 'tenantId';
export const TENANT_ATTRIBUTE = `custom:${TENANT_ATTRIBUTE_NAME}`;

/** pool-per-tenant: pool name prefix (spec §7.1). */
