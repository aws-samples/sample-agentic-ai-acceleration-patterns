import { awscdk, javascript } from 'projen';

const cdkVersion = '2.274.0';

const project = new awscdk.AwsCdkTypeScriptApp({
  cdkVersion,
  defaultReleaseBranch: 'main',
  github: false,
  name: 'tenant-identity',
  description: 'Tenant identity with Amazon Cognito in three user-pool topologies plus a mixed tiered mode, with token narrowing (RFC 8693)',
  packageManager: javascript.NodePackageManager.NPM,
  license: 'MIT-0',
  copyrightOwner: 'Amazon.com, Inc. or its affiliates. All Rights Reserved.',
  copyrightPeriod: '',
  projenrcTs: true,
  // Node 24 is the baseline this sample is built and tested on. projen writes
  // it to package.json `engines.node` (>=24) so npm install warns on an older
  // runtime, and pins the devContainer/CI node version off the same value.
  minNodeVersion: '24.0.0',
  // The test compile (`tsc --noEmit -p test/tsconfig.json`, and ts-jest, which
  // uses the same tsconfig) needs two compiler options on top of the inherited
  // src config:
  //   - skipLibCheck: the standalone test tsc otherwise fails inside
  //     @types/sinon, which references a @sinonjs/fake-timers type the installed
  //     version no longer exports (FakeTimerInstallOpts). The mismatch is in an
  //     external .d.ts we do not control; skipping library type-checking for the
  //     test compile only leaves the src compile (tsconfig.json) unaffected.
  //   - isolatedModules: ts-jest emits TS151002 on every run because the project
  //     uses the hybrid NodeNext module kind, which ts-jest only supports with
  //     isolatedModules. Setting it in the tsconfig (not the deprecated ts-jest
  //     transform option) silences the warning the way current ts-jest asks for.
  //     Per-file transpilation is exactly ts-jest's model, so nothing is lost.
  tsconfigDev: {
    compilerOptions: {
      skipLibCheck: true,
      isolatedModules: true,
    },
  },
  deps: [
    // Smithy SSDK runtime (generated code in src/smithy imports these -
    // mirror the dependency set of the generated SSDK package.json)
    'tslib@2.8.1',
    '@aws-sdk/core@3.977.9',
    '@smithy/core@3.33.3',
    '@smithy/fetch-http-handler@5.7.2',
    '@smithy/node-http-handler@4.11.3', // also imported directly: the token path's DynamoDB socket timeouts
    '@smithy/server-common@0.4.2',
    '@smithy/server-apigateway@0.3.3',
    '@smithy/types@4.17.2',
    // Runtime
    '@aws-sdk/client-cognito-identity-provider@3.1154.0',
    '@aws-sdk/client-dynamodb@3.1154.0',
    '@aws-sdk/lib-dynamodb@3.1154.0',
    '@aws-sdk/client-api-gateway@3.1154.0', // per-tenant API keys (ADR-0025)
    '@aws-sdk/client-sts@3.1154.0', // tenant-scoped role session (ADR-0026)
    'aws-jwt-verify@5.2.1', // tenant authoriser (ADR-0007)
    'ulid@3.0.2', // tenant id generation
    // Security linting - AwsSolutionsChecks aspect applied in src/main.ts
    'cdk-nag@3.0.2',
  ],
  devDeps: [
    '@types/node@24.19.2',
    '@types/aws-lambda@8.10.164',
    'aws-sdk-client-mock@4.1.0',
    'aws-sdk-client-mock-jest@4.1.0',
    'fast-check@4.10.2', // property test: narrowing never widens (ADR-0010)
    'esbuild@0.28.2', // local NodejsFunction bundling, no Docker needed
    // End-to-end scenario (test/e2e): SigV4 calls to the platform API and
    // stack discovery through CloudFormation outputs
    '@aws-sdk/client-cloudformation@3.1154.0',
    '@aws-sdk/client-ssm@3.1154.0', // e2e: R-6 parameter check
    '@aws-sdk/client-iam@3.1154.0', // e2e: ADR-0026 policy simulation
    '@aws-sdk/credential-providers@3.1154.0',
    '@aws-crypto/sha256-js@5.2.0',
    '@smithy/signature-v4@5.7.4',
    '@smithy/protocol-http@5.6.2',
  ],
  jestOptions: {
    jestConfig: {
      // Jest defaults to one worker per CPU and ts-jest holds a TypeScript
      // compiler in each (~1 GB). On a 16-core box that is 15 GB+ and gets
      // the build OOM-killed, so cap the workers and recycle leaky ones.
      maxWorkers: 4,
      workerIdleMemoryLimit: '1GB',
      // e2e suites run against deployed stacks through their own task
      testPathIgnorePatterns: ['/node_modules/', '/test/e2e/'],
      coveragePathIgnorePatterns: ['/node_modules/', '/test/', '/src/smithy/'],
    },
  },
});

// Smithy-generated SSDK output is not linted (regenerated by `smithy build`)
project.eslint?.addIgnorePattern('src/smithy/**/*');

// Generated output is not committed - `smithy build` recreates it before compile
project.gitignore.exclude('src/smithy/');

// Local working notes and agent config - not part of the sample
project.gitignore.exclude('TODO.md');
project.gitignore.exclude('.kiro/');

// The integ task's cloud assembly is machine output (scripts/integ.sh).
project.gitignore.exclude('cdk.integ.out/');
project.gitignore.exclude('cdk.integ-cp.out/');

// Holmes MCP keeps its local project link here.
project.gitignore.exclude('.holmes/');

// ASH writes its reports here (.ash/.ash.yaml is committed).
project.gitignore.exclude('.ash/ash_output/');

// Regenerate the SSDKs + OpenAPI documents from the model before every compile
project.preCompileTask.exec('smithy build');

// ---------------------------------------------------------------------------
// Build-time synth context. src/main.ts fails fast without `topology`
// (spec P-7), so `npx projen build` names one explicitly. Topology is not a
// placeholder: a deploy runs its own synth with the deployer's --context.
// Unit tests synthesise all three topologies.
// ---------------------------------------------------------------------------
const buildContext = '--context topology=shared-pool-multi-tenant';
project.tasks.tryFind('synth:silent')?.reset(`cdk synth -q ${buildContext}`);
project.tasks.tryFind('synth')?.reset(`cdk synth ${buildContext}`);

// ---------------------------------------------------------------------------
// End-to-end scenario (spec §10) against already-deployed stacks. Discovers
// each stack through its CloudFormation outputs and runs the same suite once
// per topology, in parallel (one jest worker per topology).
//   E2E_STACK_PREFIX  stack name prefix (default TenantIdentity)
//   E2E_TOPOLOGIES    comma-separated subset (default: all three)
// ---------------------------------------------------------------------------
const e2e = project.addTask('e2e', {
  description: 'Run the spec §10 scenario against deployed stacks in $AWS_REGION',
});
e2e.exec(
  'sh -c \'[ -n "$AWS_REGION" ] || { echo "Set AWS_REGION to the Region the stacks are deployed in"; exit 1; }\'',
);
e2e.exec('jest --config test/e2e/jest.config.json --runInBand=false');

// ---------------------------------------------------------------------------
// Deployment integration test (test/integ.identity.ts, scripts/integ.sh).
// Deploys the three topology stacks at once with the CDK CLI, runs the e2e
// scenario, then always destroys them at once (ADR-0023). Must run in
// EXACTLY ONE explicitly selected Region (README "Deployment integration
// test"); the script fails fast when AWS_REGION is unset.
// ---------------------------------------------------------------------------
const integ = project.addTask('integ', {
  description:
    'Run the deployment integration test in $AWS_REGION (deploys four stacks to the current AWS account)',
});
integ.exec('scripts/integ.sh');

// Control-plane mounting integration test (mounting spec §10,
// test/integ.control-plane.ts, scripts/integ-control-plane.sh). Deploys
// tenant-identity (shared-pool) and a setup stack, then control-plane through
// its own deploy path, runs the scenario, and always destroys all three.
const integCp = project.addTask('integ:control-plane', {
  description:
    'Run the control-plane mounting integration test in $AWS_REGION (deploys tenant-identity, a setup stack and ../control-plane)',
});
integCp.exec('scripts/integ-control-plane.sh');

project.synth();
